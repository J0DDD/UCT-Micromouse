"""Build a compact copy of the mouse code for the robot's 64 KB /flash drive.

The source files are heavily commented; MicroPython compiles them on the
robot, so comments and docstrings cost flash space and RAM for nothing. This
parses each module with Python's own parser, drops docstrings and comments,
and writes the result to <repo>/build/task2_robot/, ready for:

    python tools/deploy.py --engine micropython --src-dir build/task2_robot

or, if deploy.py cannot connect ("could not enter raw repl" - the board's
soft reset confuses mpremote), upload directly with this script:

    python workspace/task2_maze/build_robot.py --port COM10

which copies the files with `mpremote connect <port> resume ...` (no soft
reset), then hard-resets the board so the new files are actually used.

By default each module is also precompiled with mpy-cross (pip install
mpy-cross==1.29.0.post2, matching the firmware's .mpy v6.3) so the robot never
compiles source at boot - compiling ~50 KB on the robot can fail with
MemoryError. main.py is then a small loader for mission.mpy. --source ships
the stripped .py files instead.
"""
import argparse
import ast
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(REPO, "build", "task2_robot")
MODULES = ["config.py", "maze.py", "motion.py", "main.py", "calibrate.py"]
EXTRA = ["polarity.txt"]            # copied as-is if present
FLASH_BUDGET = 58 * 1024            # /flash held 41 KB of code with 35 KB still free


class StripDocstrings(ast.NodeTransformer):
    def _strip(self, node):
        self.generic_visit(node)
        body = node.body
        if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant) \
                and isinstance(body[0].value.value, str):
            body = body[1:] or [ast.Pass()]
        node.body = body
        return node

    visit_Module = _strip
    visit_FunctionDef = _strip
    visit_ClassDef = _strip


LOADER = """# main.py - loader generated by build_robot.py --mpy.
# The real code is precompiled in mission.mpy (and the other .mpy modules),
# so the robot never compiles Python source itself (avoids MemoryError at boot).
import uct_mouse
import mission
try:
    mission.main()
finally:
    uct_mouse.set_motors(0, 0)
"""


def upload(port, files, stale):
    base = [sys.executable, "-m", "mpremote", "connect", port, "resume"]
    # remove source copies of modules now shipped as .mpy (MicroPython would
    # import a leftover .py in preference to the new .mpy)
    for name in stale:
        subprocess.run(base + ["fs", "rm", ":" + name], capture_output=True)
    for name in files:
        print("uploading %s ..." % name)
        subprocess.run(base + ["fs", "cp", os.path.join(OUT, name), ":" + name], check=True)
    out = subprocess.run(base + ["exec", "import os; print(os.listdir('/flash')); s = os.statvfs('/flash'); print('free bytes:', s[0] * s[3])"],
                         check=True, capture_output=True, text=True)
    print(out.stdout.strip())
    # Hard reset: with `resume` the board's Python session survives between
    # connections, so modules imported earlier would otherwise stay cached and
    # the new files would not be used until the next reset.
    subprocess.run(base + ["exec", "import machine; machine.reset()"], capture_output=True)
    print("done - the mouse has been reset and runs the new main.py")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--port", help="also upload to the mouse on this serial port (e.g. COM10)")
    ap.add_argument("--source", action="store_true",
                    help="ship stripped .py source instead of precompiled .mpy (needs more robot RAM)")
    args = ap.parse_args()
    use_mpy = not args.source
    if os.path.exists(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    total = 0
    stale = []
    for name in MODULES:
        src = open(os.path.join(HERE, name), encoding="utf-8").read()
        tree = StripDocstrings().visit(ast.parse(src))
        code = "# built from workspace/task2_maze/%s by build_robot.py - edit the original\n" % name
        code += ast.unparse(tree) + "\n"
        compile(code, name, "exec")             # sanity check
        out_name = name
        if use_mpy and name == "main.py":
            out_name = "mission.py"             # main.py becomes a tiny loader
        path = os.path.join(OUT, out_name)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(code)
        if use_mpy:
            subprocess.run([sys.executable, "-m", "mpy_cross", "-o", path[:-3] + ".mpy", path], check=True)
            os.remove(path)
            out_name = out_name[:-3] + ".mpy"
            if name != "main.py":
                stale.append(name)
        size = os.path.getsize(os.path.join(OUT, out_name))
        total += size
        print("%-13s %6d -> %-13s %6d bytes" % (name, len(src.encode()), out_name, size))
    if use_mpy:
        with open(os.path.join(OUT, "main.py"), "w", encoding="utf-8", newline="\n") as f:
            f.write(LOADER)
        total += len(LOADER)
        stale.append("mission.py")
    for name in EXTRA:
        p = os.path.join(HERE, name)
        if os.path.exists(p):
            shutil.copy(p, OUT)
            total += os.path.getsize(p)
    print("total %d bytes (%.0f%% of the %d KB budget) -> %s" % (
        total, 100.0 * total / FLASH_BUDGET, FLASH_BUDGET // 1024, OUT))
    if total > FLASH_BUDGET:
        print("WARNING: over budget")
        sys.exit(1)
    if args.port:
        upload(args.port, sorted(os.listdir(OUT)), stale if use_mpy else [])


if __name__ == "__main__":
    main()
